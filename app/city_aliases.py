def _compact(value: str | None) -> str:
    """Название без регистра, пробелов, точек и дефисов, «ё» = «е».

    «Мин Воды», «мин.воды», «МИН-ВОДЫ» и «Минводы» дают одну строку «минводы».
    Раньше справочник искал точную строку в нижнем регистре, и любое отличие
    (лишний пробел, заглавная буква, точка) делало город «новым»: в автодополнении
    фильтра появлялось три «Минеральных Воды», а фильтр по одной записи не находил
    остальные.
    """
    text = str(value or "").lower().replace("ё", "е")
    return re.sub(r"[^0-9a-zа-я]+", "", text)


def _build_alias_index() -> dict[str, str]:
    index: dict[str, str] = {}
    for alias, canonical in CITY_ALIASES.items():
        index[_compact(alias)] = canonical
        index[_compact(canonical)] = canonical
    return index


_ALIAS_INDEX: dict[str, str] = _build_alias_index()


def canonical_city_name(raw: str | None) -> str | None:
    """Каноническое название, если ``raw`` — известный город или его написание/сокращение.

    Единственная точка стандарта: точное совпадение по «сжатой» форме (см.
    :func:`_compact`), без угадывания по началу строки. ``None`` — город не из
    справочника, его название остаётся как написано.
    """
    if not raw:
        return None
    return _ALIAS_INDEX.get(_compact(city_key(raw)))


@lru_cache(maxsize=32768)
def expand_city_term(raw: str) -> str:
    """Раскрывает сокращение в полное название города. Если сокращение
    неизвестно — возвращает исходный текст как есть (сравнение всё равно
    идёт как substring, так что не-раскрытые города продолжают работать)."""
    term = raw.strip()
    if not term:
        return term
    exact = canonical_city_name(term)
    if exact:
        return exact
    # Частичное совпадение по префиксу в любую сторону — так "минеральные"
    # находит "минеральные воды", а "минвод" находит алиас "минводы".
    compact = _compact(city_key(term))
    if not compact:
        return term
    for alias, canonical in CITY_ALIASES.items():
        alias_compact = _compact(alias)
        if alias_compact.startswith(compact) or compact.startswith(alias_compact):
            return canonical
    return term


def city_matches(term: str, order_city: str | None) -> bool:
    """Совпадает ли один поисковый термин (город из фильтра) с городом
    заказа — с учётом сокращений в обе стороны."""
    if not order_city:
        return False
    term = term.strip()
    if not term:
        return True
    term_l = term.lower()
    order_l = order_city.lower()
    if term_l in order_l:
        return True
    term_canon = expand_city_term(term).lower()
    order_canon = expand_city_term(order_city).lower()
    return term_canon in order_canon or term_canon in order_l or term_l in order_canon


def split_city_terms(raw: str) -> list[str]:
    """Несколько городов через запятую — водитель может искать сразу по
    паре направлений."""
    return [t.strip() for t in raw.split(",") if t.strip()]


@lru_cache(maxsize=32768)
def city_key(value: str | None) -> str:
    """Нормализованная форма названия города — для сравнения прямо в SQL.

    Приводим к нижнему регистру и убираем мусор («г.», «город»), чтобы
    «Симферополь», «симферополь» и «г. Симферополь» давали один ключ.
    ВАЖНО: используется именно Python-овский .lower(), потому что lower()
    в SQLite понимает только ASCII и кириллицу не приводит.
    """
    if not value:
        return ""
    text = str(value).strip().lower().replace("ё", "е")
    for _ in range(2):  # «г. п. Мостовской» — два префикса подряд
        text = _CITY_PREFIX_RE.sub("", text)
    # «М.О.» и «М. О.» — одно и то же: точки считаем пробелами.
    text = re.sub(r"[.\s]+", " ", text)
    text = re.sub(r"\s*\(\s*", " (", text)  # «Толстое( Район )» = «Толстое (Район)»
    text = re.sub(r"\s*\)", ")", text)
    return text.strip(" .,;-")


def canonical_city_variants(raw: str) -> list[str]:
    """Все формы, которыми город из фильтра может быть записан в заявке.

    Возвращает ключи (см. :func:`city_key`) в нижнем регистре: сам термин,
    его каноническое раскрытие и все известные алиасы того же города. Дальше
    SQL-фильтр ищет ``LIKE '%вариант%'`` по подготовленным колонкам
    ``from_city_key``/``to_city_key`` — без функций регистра в самой БД.
    """
    term = (raw or "").strip()
    if not term:
        return []
    variants: list[str] = []
    seen: set[str] = set()

    def _add(value: str | None) -> None:
        key = city_key(value)
        if key and key not in seen:
            seen.add(key)
            variants.append(key)

    _add(term)
    canonical = expand_city_term(term)
    _add(canonical)
    canonical_key = city_key(canonical)
    for alias, alias_canonical in CITY_ALIASES.items():
        if city_key(alias_canonical) == canonical_key:
            _add(alias)
    return variants


