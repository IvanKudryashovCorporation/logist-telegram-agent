"""Пометки диспетчера «заказ закрыт»: закрытый замок, ❌❌❌ или слова «Отдан ✅», «Забрали», «Закрыт».

Диспетчер редактирует своё сообщение и дописывает 🔒 (или 🔐): заказ взяли. Три креста ❌❌❌ —
заказ неактуален. Открытый замок 🔓 — «свободно», с ним всё хорошо. Заявка с такой пометкой снимается
с ленты, а уведомление о ней у водителя в Telegram удаляется.

Слова «отдан», «забрали», «закрыт» считаем пометкой, только если они стоят отдельной строкой или рядом с галочкой:
в середине обычной фразы («отдан на руки водителю») это не отметка.
"""

import re

from app.parsing.not_orders import has_cancel_mark

#: Закрытый замок, замок с ключом и замок с пером. Открытый замок (🔓) сюда не входит.
CLOSED_LOCKS = ("\U0001F512", "\U0001F510", "\U0001F50F")

#: Действие журнала, по которому заявка снята из-за замка.
ACTION_CLOSED_LOCK = "cancelled_closed_lock"


#: Слова, которыми диспетчер отмечает, что заказ ушёл или не нужен.
_CLOSED_WORD = (
    r"(?:отдан\w*|забрал[иа]|взяли|взят[оа]?|закрыт\w*|выполнен\w*|занят[оаы]?"
    r"|не\s*актуальн\w*|неактуальн\w*|сняли|снят[оа]?)(?!\w)"
)
#: Строка целиком состоит из такого слова (и знаков/эмодзи вокруг): «Отдан ✅», «Забрали!», «Не актуально».
_CLOSED_LINE_RE = re.compile(rf"^[\W_]*{_CLOSED_WORD}[\W_]*$", re.IGNORECASE | re.MULTILINE)
#: Слово и галочка в одной строке рядом: «Заказ отдан ✅», «✅ взяли».
_CLOSED_TICK_RE = re.compile(
    rf"{_CLOSED_WORD}[^\n]{{0,15}}[✅✔☑]|[✅✔☑][^\n]{{0,15}}{_CLOSED_WORD}", re.IGNORECASE
)


def has_closed_mark(text: str | None) -> bool:
    """Диспетчер словами отметил, что заказ ушёл: «Отдан ✅», «Забрали», «Не актуально»."""
    return bool(text) and bool(_CLOSED_LINE_RE.search(text) or _CLOSED_TICK_RE.search(text))


def has_closed_lock(text: str | None) -> bool:
    """В тексте есть закрытый замок, ❌❌❌ или слова «Отдан ✅» (заказ закрыт или неактуален)."""
    return bool(text) and (
        any(lock in text for lock in CLOSED_LOCKS) or has_cancel_mark(text) or has_closed_mark(text)
    )
