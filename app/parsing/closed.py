"""Пометки диспетчера «заказ закрыт»: закрытый замок или ❌❌❌ в тексте заявки.

Диспетчер редактирует своё сообщение и дописывает 🔒 (или 🔐): заказ взяли. Три креста ❌❌❌ —
заказ неактуален. Открытый замок 🔓 — «свободно», с ним всё хорошо. Заявка с такой пометкой снимается
с ленты, а уведомление о ней у водителя в Telegram удаляется.
"""

from app.parsing.not_orders import has_cancel_mark

#: Закрытый замок, замок с ключом и замок с пером. Открытый замок (🔓) сюда не входит.
CLOSED_LOCKS = ("\U0001F512", "\U0001F510", "\U0001F50F")

#: Действие журнала, по которому заявка снята из-за замка.
ACTION_CLOSED_LOCK = "cancelled_closed_lock"


def has_closed_lock(text: str | None) -> bool:
    """В тексте есть закрытый замок или ❌❌❌ (заказ закрыт или неактуален)."""
    return bool(text) and (any(lock in text for lock in CLOSED_LOCKS) or has_cancel_mark(text))
