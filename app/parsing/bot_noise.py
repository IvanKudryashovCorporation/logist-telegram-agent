"""Служебные строки бота-агрегатора («PRO все заказы»), которые не относятся к заявке.

Бот под каждой заявкой пишет своё «Сообщение диспетчеру уже вписано…» с готовым текстом, подсказку про
закрытую группу и время публикации («только что», «16 минут назад»). Для нас это шум: собственный текст
диспетчеру сайт строит сам (``app.web.presenters.dispatcher_message``), а меняющееся время публикации
мешало бы кэшу разбора и поиску копий — один и тот же заказ приходил бы с разным текстом.

Строка с контактом («👤 Диспетчер: @имя», «📞 Телефон: …») остаётся: по ней находится диспетчер.
"""

import re
from typing import Final

#: Целиком вырезаем строки, где встречается любой из этих признаков.
_NOISE_LINE: Final[re.Pattern[str]] = re.compile(
    # Готовый текст диспетчеру бывает на следующей строке («…и отправьте:⏎Здравствуйте! Возьму заказ…»): уходит с ней.
    r"^[^\n]*Сообщение диспетчеру уже вписано[^\n]*:[ \t]*\n(?![ \t]*(?:👤|ℹ|📞))[^\n]*(?:\n|$)"
    r"|^[^\n]*(?:Сообщение диспетчеру уже вписано|«Источник» откроется|Опубликован:)[^\n]*(?:\n|$)",
    re.MULTILINE,
)


def strip_bot_noise(text: str) -> str:
    """Текст без служебных строк бота; сообщения других источников возвращает как есть."""
    if not text or not _NOISE_LINE.search(text):
        return text
    cleaned = _NOISE_LINE.sub("", text)
    return re.sub(r"\n{3,}", "\n\n", cleaned).strip()
