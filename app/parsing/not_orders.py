"""Сообщения, которые выглядят как заявка, но заявкой не являются или уже неактуальны.

Два случая, которые модель и фильтры пропускали на проде:

* **Предложение водителя.** Водитель пишет, куда едет сам и что «есть места»
  («В воскресенье 11.10 утром еду Горловка-Ростов. После обеда обратно. Есть места без пешего
  перехода»). Заказа тут нет, сайт показывает только заказы клиентов от диспетчеров.
* **Крест ❌❌❌.** Диспетчер редактирует заявку и дописывает три креста: заказ неактуален.
  Один крест — обычная пометка в тексте заявки («животные ❌»), снимаем только от трёх подряд.

Правила узкие: ловят однозначные формулировки, а сомнительное уходит в модель. Решение каждый раз
пишется в лог и в ``parse_stats`` (``driver_offer``), чтобы владелец мог проверить срабатывания.
"""

import re
from typing import Final, Optional

#: Причины, по которым заказ снимается.
REASON_DRIVER_OFFER: Final[str] = "driver_offer"
REASON_CANCEL_MARK: Final[str] = "cancel_mark"

#: Три и более ❌ подряд (с вариантами оформления и пробелами между ними).
_CANCEL_MARK_RE: Final[re.Pattern[str]] = re.compile(r"(?:\u274c\ufe0f?[\s\u200d]*){3,}")

#: «Есть места», «есть 2 свободных места», «свободные места», «места есть»: так предлагает поездку
#: водитель; у диспетчера в заявке пишут число пассажиров, а не наличие мест.
_SEATS_RE: Final[re.Pattern[str]] = re.compile(
    r"\bесть\s+(?:\d+\s+)?(?:свободн\w+\s+)?мест[оаы]?\b"
    r"|\bсвободн\w*\s+мест"
    r"|\bмест[аоы]?\s+(?:есть|свободн)",
    re.IGNORECASE,
)

#: «Возьму попутчиков», «заберу 2 пассажиров», «ищу попутчиков» — водитель набирает людей.
_RECRUIT_RE: Final[re.Pattern[str]] = re.compile(
    r"\b(?:возьму|заберу|подберу|беру|возьмём|возьмем|набираю)\s+(?:\d+\s+)?(?:пассажир\w*|попутчик\w*|людей|человек\w*)"
    r"|\bищу\s+(?:попутчик|пассажир|компаньон)",
    re.IGNORECASE,
)


#: Крест рядом со словом о закрытии: «❌закрыт❌», «ОТМЕНА КЛИЕНТОМ ❌», «❌ Отдан». Один-два креста сами по себе
#: ничего не значат («страховка❌❌» — страховка не включена), поэтому нужно ещё и слово.
_CANCEL_WORD_RE: Final[re.Pattern[str]] = re.compile(
    r"❌[^\n]{0,20}(?:закрыт|отмен|отдан|не\s*актуал)"
    r"|(?:закрыт|отмен|отдан|не\s*актуал)[^\n]{0,20}❌",
    re.IGNORECASE,
)


def has_cancel_mark(text: Optional[str]) -> bool:
    """Диспетчер пометил заявку неактуальной: три и более ❌ подряд или ❌ рядом со словом «закрыт»/«отмена»."""
    return bool(text) and bool(_CANCEL_MARK_RE.search(text) or _CANCEL_WORD_RE.search(text))


def is_driver_offer(text: Optional[str]) -> bool:
    """Водитель предлагает поездку (есть места, ищу попутчиков), а не диспетчер ищет машину."""
    if not text:
        return False
    return bool(_SEATS_RE.search(text) or _RECRUIT_RE.search(text))


def non_order_reason(text: Optional[str]) -> Optional[str]:
    """Почему заказ из этого текста надо снять (или не создавать), если причина есть."""
    if has_cancel_mark(text):
        return REASON_CANCEL_MARK
    if is_driver_offer(text):
        return REASON_DRIVER_OFFER
    return None
